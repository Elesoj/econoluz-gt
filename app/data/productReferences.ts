export const validatePermanentReferences = (
  internalIds: readonly string[],
  references: Readonly<Record<string, string>> = productReferenceByInternalId,
) => {
  const seenReferences = new Set<string>();

  for (const internalId of internalIds) {
    const reference = references[internalId];

    if (!reference) {
      throw new Error(`missing permanent reference for ${internalId}`);
    }

    if (seenReferences.has(reference)) {
      throw new Error(`duplicate permanent reference ${reference}`);
    }

    seenReferences.add(reference);
  }
};

