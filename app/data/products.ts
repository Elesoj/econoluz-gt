const getPlateFinish = (code: string) => {
  if (code.startsWith("APL-3")) {
    return "Negro mate";
  }

  if (code.startsWith("APL-2") || code === "APL-001" || code === "APL-002") {
    return "Blanco brillante";
  }

  return "Gris metálico";
};

