const normalizeProduct = ({
  brand,
  category,
  subcategory,
  collection,
  application,
  finish = "",
  ...product
}: RawProduct, index: number) => {
  const brandId = getBrandId(brand);
  const productTypeId = getProductTypeId(category);
  const applicationId = getApplicationId(application);
  const seriesSource = collection ?? subcategory ?? "";
  const seriesId = getSeriesId(seriesSource);
  const finishId = getFinishId(finish);
  const publicTechnicalSpecs = sanitizeTechnicalSpecs(product.technicalSpecs);

  return {
    ...product,
    publicName: buildPublicName({ category, application, subcategory }),
    publicDescription: sanitizeSupplierText(product.description),
    technicalSpecs: publicTechnicalSpecs,
    econoluzReference: buildEconoluzReference(category, index),
    supplierCode: product.sku,
    supplierBrand: brandId,
    brand: brandId,
    productType: productTypeId,
    application: applicationId,
    series: seriesId,
    finish: finishId,
    labels: {
      brand: getBrandLabel(brandId),
      productType: getProductTypeLabel(productTypeId),
      application: getApplicationLabel(applicationId),
      series: getSeriesLabel(seriesId) === seriesId ? seriesSource : getSeriesLabel(seriesId),
      family: subcategory ?? seriesSource,
      finish: getFinishLabel(finishId) === finishId ? finish : getFinishLabel(finishId),
    },
  };
};

export const products = rawProducts.map((product, index) => normalizeProduct(product, index));

export type Product = (typeof products)[number];
